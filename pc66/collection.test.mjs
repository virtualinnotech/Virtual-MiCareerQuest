import assert from 'node:assert/strict';
import {create} from './core.js';
import {parts,buildSteps,bootSteps} from './curriculum.js';
import {builds,rewardState,earnReward} from './collection.js';
const fresh=create(),reward=rewardState(null);
assert.equal(earnReward(reward,fresh),false);
assert.equal(reward.unlocked,false);
const complete=create({version:2,phase:'complete',learned:parts.map(p=>p.id),step:buildSteps.length,boot:bootSteps.length});
assert.equal(earnReward(reward,complete),true);
assert.equal(earnReward(reward,complete),false);
reward.selected='rose';
const restored=rewardState(JSON.parse(JSON.stringify(reward)));
assert.equal(restored.selected,'rose');
assert.equal(create(restored.certificate).state.completed,true);
assert.equal(earnReward(restored,create()),false);
assert.equal(restored.unlocked,true,'practice restart cannot erase earned collection');
assert.equal(restored.selected,'rose');
assert.equal(rewardState({...reward,selected:'invalid'}).selected,'original');
assert.equal(rewardState({unlocked:true}).unlocked,false);
assert.equal(new Set(builds.map(b=>b.id)).size,11);
console.log('PASS locked fresh visit, first completion unlock, legacy completion, persistent selection, restart preservation, 11 unique choices');
